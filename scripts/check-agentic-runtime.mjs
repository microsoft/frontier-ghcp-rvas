import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export function checkRuntime(text, filename) {
  const lines = text.split(/\r?\n/);
  const metadataLine = lines.find(line => line.startsWith('# gh-aw-metadata: '));
  const manifestLine = lines.find(line => line.startsWith('# gh-aw-manifest: '));
  const compiler = metadataLine
    ? JSON.parse(metadataLine.slice('# gh-aw-metadata: '.length)).compiler_version
    : text.match(/^# This file was automatically generated by .+ \((v[\d.]+)\)\./m)?.[1];
  if (!compiler) return [`${filename}: missing gh-aw compiler version`];

  const manifest = manifestLine
    ? JSON.parse(manifestLine.slice('# gh-aw-manifest: '.length))
    : null;
  const errors = [];
  let runtimeActions = 0;
  for (const [index, line] of lines.entries()) {
    if (!/^\s*uses:\s+github\/(?:gh-aw-actions\/|gh-aw\/actions\/)/.test(line)) continue;
    runtimeActions++;
    const location = `${filename}:${index + 1}`;
    const pin = line.match(/uses:\s+([^@\s]+)@([a-f0-9]{40})\s+#\s*(v[\d.]+)\s*$/);
    if (!pin) {
      errors.push(`${location}: gh-aw runtime needs a SHA pin and compiler-version comment`);
      continue;
    }
    const [, repo, sha, version] = pin;
    if (version !== compiler) {
      errors.push(`${location}: ${repo} uses ${version}, but the workflow was compiled with ${compiler}`);
    }
    if (manifest) {
      const declared = manifest.actions?.find(action => action.repo === repo);
      if (!declared || declared.sha !== sha || declared.version !== version) {
        errors.push(`${location}: ${repo} pin differs from the generated manifest`);
      }
    }
  }
  if (!runtimeActions) errors.push(`${filename}: no gh-aw runtime setup actions found`);
  return errors;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const directory = join(root, '.github', 'workflows');
  const files = readdirSync(directory)
    .filter(name => name.endsWith('.lock.yml') || name === 'agentics-maintenance.yml')
    .sort();
  if (!files.length) throw new Error('No generated agentic workflows found');
  const errors = files.flatMap(name => checkRuntime(readFileSync(join(directory, name), 'utf8'), name));
  if (errors.length) {
    console.error(errors.join('\n'));
    console.error('Recompile with the matching gh-aw version; do not update runtime pins independently.');
    process.exitCode = 1;
  } else {
    console.log(`Runtime versions and manifest pins match in ${files.length} generated workflows.`);
  }
}
